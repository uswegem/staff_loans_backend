const DEFAULT_COUNTRY = 'Tanzania';

/** Older free-text values that name a country on the list. */
const ALIASES = Object.freeze({ tanzanian: 'Tanzania', 'united republic of tanzania': 'Tanzania' });

/** The country on the list for a value (case-insensitive, or a known alias); null when there is none. */
function normaliseCountry(value) {
  if (typeof value !== 'string' || !value.trim()) return null;
  const t = value.trim().toLowerCase();
  return COUNTRIES.find((c) => c.toLowerCase() === t) || ALIASES[t] || null;
}

module.exports = { COUNTRIES, DEFAULT_COUNTRY, normaliseCountry };
