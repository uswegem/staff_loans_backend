'use strict';

// A fictional payslip PDF for seeds and tests (D-79), laid out like LFB's SeamlessHR
// payslip: a "Payslip for <Month> <Year>" header, employee details as label rows over
// value rows, then Earnings and Employee Deductions tables with amounts on the right.
// The bank's name and an account number appear on it, as on the real one, so tests
// show the reader does not mistake them for LFB deductions. Every value is fictional.

const { PDFDocument, StandardFonts, rgb } = require('pdf-lib');
const calc = require('../src/services/calc/loanCalculator');

const money = (n) => `${Math.round(n).toLocaleString('en-US')}.00`;
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/**
 * staff: { fullName, staffNo, title, department }; basic, allowances; payDate 'YYYY-MM-DD'
 * (its month is printed); lfbLines: [{ label, amount }] (default label STAFF LOAN);
 * pricing: for pension and PAYE.
 */
async function samplePayslip({ staff, basic, allowances = 0, payDate, lfbLines = [], pricing }) {
  const ps = calc.payslip({ basic, lfbDeductions: 0 }, pricing);
  const doc = await PDFDocument.create();
  const page = doc.addPage([595.28, 841.89]);
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.1, 0.1, 0.1);
  let y = 800;
  const text = (t, x, opts = {}) => page.drawText(t, { x, y, size: opts.size || 9, font: opts.bold ? bold : font, color: ink });
  const right = (t, xRight, opts = {}) => text(t, xRight - (opts.bold ? bold : font).widthOfTextAtSize(t, opts.size || 9), opts);
  const [yy, mm] = payDate.split('-');

  text('Letshego Faidika Bank', 40, { bold: true, size: 13 });
  right(`Payslip for ${MONTHS[Number(mm) - 1]} ${yy}`, 555, { bold: true });
  y -= 20;
  text('Address: P.O. Box 0000, Dar-es-Salaam, Tanzania (SAMPLE - FICTIONAL DATA)', 40, { size: 8 });
  y -= 26;
  text('EMPLOYEE INFORMATION', 40, { bold: true });
  y -= 18;
  const info = [
    [['NAME', staff.fullName], ['EMPLOYEE CODE', staff.staffNo], ['JOB ROLE', staff.title || '']],
    [['EMPLOYMENT DATE', '2020-01-06'], ['LOCATION', 'Head Office'], ['PAY GRADE', '7']],
    [['PAY GROUP', staff.department || 'Staff'], ['BANK NAME', 'Letshego Faidika Bank'], ['ACCOUNT NUMBER', '20000000000']],
  ];
  for (const row of info) {
    row.forEach(([label], i) => text(label, 40 + i * 180, { size: 8 }));
    y -= 12;
    row.forEach(([, value], i) => text(value, 40 + i * 180, { bold: true }));
    y -= 18;
  }

  y -= 8;
  text('EARNINGS INFORMATION', 40, { bold: true });
  y -= 18;
  text('EARNINGS', 40, { bold: true });
  right('AMOUNT (TZS)', 555, { bold: true });
  y -= 16;
  const earnings = [['Basic', basic], ...(allowances ? [['Housing Allowance', allowances]] : [])];
  for (const [label, amount] of earnings) {
    text(label, 40);
    right(money(amount), 555);
    y -= 16;
  }
  const gross = basic + allowances;
  text('Gross', 40, { bold: true });
  right(money(gross), 555, { bold: true });
  y -= 28;

  text('EMPLOYEE DEDUCTIONS', 40, { bold: true });
  y -= 18;
  text('EMPLOYEE DEDUCTIONS', 40, { bold: true });
  right('AMOUNT (TZS)', 555, { bold: true });
  y -= 16;
  const deductions = [['Tax', ps.tax], ['Pension', ps.pension], ...lfbLines.map((l) => [l.label || 'STAFF LOAN', l.amount])];
  for (const [label, amount] of deductions) {
    text(label, 40);
    right(money(amount), 555);
    y -= 16;
  }
  const total = deductions.reduce((s, d) => s + d[1], 0);
  text('Total Deductions', 40, { bold: true });
  right(money(total), 555, { bold: true });
  y -= 26;
  text('NET PAY', 40, { bold: true });
  right(money(gross - total), 555, { bold: true });
  y -= 30;
  right(`${yy}. Letshego Faidika Bank. Generated by a payroll system (sample).`, 555, { size: 8 });
  return Buffer.from(await doc.save());
}

module.exports = { samplePayslip };
