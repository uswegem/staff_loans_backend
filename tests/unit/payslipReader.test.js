'use strict';

// Reading Basic Pay, LFB deductions and the pay date from a payslip PDF (D-79). The
// sample payslip copies the layout of LFB's SeamlessHR payslip with fictional values.

const { PDFDocument, StandardFonts } = require('pdf-lib');
const reader = require('../../src/services/payslip/payslipReader');
const calc = require('../../src/services/calc/loanCalculator');
const { samplePayslip } = require('../../seed/samplePayslip');
const { PRICING } = require('../fixtures/products');

const STAFF = { fullName: 'Neema Mushi', firstName: 'Neema', lastName: 'Mushi', staffNo: 'LFB0412', title: 'Customer Service Officer', department: 'Branch Network' };

describe('payslip reader', () => {
  it('reads the LFB payslip layout: Basic, every staff loan and the pay month', async () => {
    const pdf = await samplePayslip({ staff: STAFF, basic: 1850000, allowances: 220000, payDate: '2026-10-25', pricing: PRICING, lfbLines: [{ label: 'STAFF LOAN', amount: 150000 }, { label: 'LFB LOAN', amount: 50000 }] });
    const out = await reader.read(pdf, { staff: STAFF });
    expect(out).toEqual({ basic: 1850000, payDate: '2026-10-31', lfbDeductions: 200000, lfbLines: [{ label: 'STAFF LOAN', amount: 150000 }, { label: 'LFB LOAN', amount: 50000 }] });
  });

  it('does not count tax, pension, totals, the bank name, the account number or the year', async () => {
    const pdf = await samplePayslip({ staff: STAFF, basic: 1850000, payDate: '2026-10-25', pricing: PRICING });
    expect(await reader.read(pdf, { staff: STAFF })).toMatchObject({ basic: 1850000, lfbDeductions: 0, lfbLines: [] });
    const lines = ['Letshego Faidika Bank  Payslip for October 2026', 'Senior Management  Letshego Faidika Bank  20000000000', '2026. Letshego Faidika Bank. Generated by SeamlessHR.com'];
    expect(reader.parse(lines, { ...reader.DEFAULT_RULES, lfbLabels: ['Letshego', 'Faidika'] })).toMatchObject({ lfbDeductions: 0, payDate: '2026-10-31' });
  });

  it('keeps the shillings and drops the cents', () => {
    expect(reader.parse(['Basic  1,234,567.89', 'STAFF LOAN  412,345.67', 'Payslip for October 2026'])).toMatchObject({ basic: 1234567, lfbDeductions: 412345 });
  });

  it('the payslip pension and tax follow the calculator (10% of Basic; PAYE on Basic less Pension)', () => {
    // LFB's October 2026 payslip showed Pension = 10% of Basic and Tax = PAYE on
    // (Basic − Pension) at the top band, to within a shilling of rounding.
    const p = calc.payslip({ basic: 12000000 }, PRICING);
    expect(p).toMatchObject({ pension: 1200000, taxable: 10800000, tax: 128000 + Math.round(0.3 * (10800000 - 1000000)) });
  });

  it('refuses a payslip for someone else', async () => {
    const pdf = await samplePayslip({ staff: { ...STAFF, fullName: 'Juma Kassim', staffNo: 'LFB0233' }, basic: 1850000, payDate: '2026-10-25', pricing: PRICING });
    expect((await reader.read(pdf, { staff: STAFF })).problem.code).toBe('PAYSLIP_NOT_YOURS');
  });

  it('matches on the employee code, which is the staff number (C-07); the name alone is not enough', () => {
    const at = { ...STAFF, staffNo: 'AT637' };
    expect(reader.namesStaff(['NAME  EMPLOYEE CODE', 'Neema Mushi  AT637'], at)).toBe(true);
    expect(reader.namesStaff(['NAME  EMPLOYEE CODE', 'Neema Mushi  AT6370'], at)).toBe(false);
    expect(reader.namesStaff(['NAME  EMPLOYEE CODE', 'Neema Mushi  AT412'], at)).toBe(false);
    expect(reader.namesStaff(['NAME  EMPLOYEE CODE', 'Someone Else  AT637'], { ...at, staffNo: 'AT63' })).toBe(false);
  });

  it('refuses a PDF without text (a scan) and a file that is not a PDF', async () => {
    const doc = await PDFDocument.create();
    doc.addPage();
    expect((await reader.read(Buffer.from(await doc.save()), { staff: STAFF })).problem.code).toBe('PAYSLIP_UNREADABLE');
    expect((await reader.read(Buffer.from('not a pdf'), { staff: STAFF })).problem.code).toBe('PAYSLIP_UNREADABLE');
  });

  it('says what is missing when the layout has no Basic Pay', async () => {
    const doc = await PDFDocument.create();
    const font = await doc.embedFont(StandardFonts.Helvetica);
    const page = doc.addPage();
    page.drawText('Neema Mushi  LFB0412   Payslip for October 2026', { x: 40, y: 700, size: 10, font });
    page.drawText('Gross 2,070,000.00', { x: 40, y: 680, size: 10, font });
    expect((await reader.read(Buffer.from(await doc.save()), { staff: STAFF })).problem.code).toBe('PAYSLIP_NO_BASIC');
  });

  it('does not read a staff number such as LFB0412 as an amount', () => {
    expect(reader.parse(['Employee: Neema Mushi  Staff No: LFB0412', 'STAFF LOAN  150,000.00', 'Basic  1,850,000.00'], { ...reader.DEFAULT_RULES, lfbLabels: ['LFB', 'Staff Loan'] })).toMatchObject({ basic: 1850000, lfbDeductions: 150000 });
  });

  it('labels come from settings, so a new layout needs no code change', () => {
    const lines = ['Mshahara wa Msingi 2,400,000', 'Tarehe ya Malipo 30/09/2026', 'Mkopo LFB 120,000'];
    const out = reader.parse(lines, { basicLabels: ['Mshahara wa Msingi'], lfbLabels: ['Mkopo LFB'], dateLabels: ['Tarehe ya Malipo'] });
    expect(out).toMatchObject({ basic: 2400000, payDate: '2026-09-30', lfbDeductions: 120000 });
  });

  it.each([
    ['31/10/2026', '2026-10-31'],
    ['2026-10-25', '2026-10-25'],
    ['25 Oct 2026', '2026-10-25'],
    ['October 2026', '2026-10-31'],
    ['February 2028', '2028-02-29'],
    ['31/02/2026', null],
  ])('reads the date %s as %s', (text, day) => {
    expect(reader.parseDate(text)).toBe(day);
  });
});
